create or replace function public.set_order_audit()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = now();
  if auth.uid() is not null then
    new.last_status_changed_by = auth.uid();
  end if;
  return new;
end;
$$;

drop trigger if exists trg_order_audit on public.orders;
create trigger trg_order_audit
before insert or update on public.orders
for each row
when (pg_trigger_depth() = 0)
execute procedure public.set_order_audit();

-- Inventory reservations prevent concurrent storefront/POS sales from
-- overselling stock while a payment is still pending.
alter table public.products
  add column if not exists stock_reserved integer not null default 0;

update public.products
set stock_reserved = 0
where stock_reserved is null;

alter table public.products
  drop constraint if exists products_stock_reserved_nonnegative;

alter table public.products
  add constraint products_stock_reserved_nonnegative
  check (stock_reserved >= 0);

