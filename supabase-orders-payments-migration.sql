create or replace function public.create_reserved_order(
  p_items jsonb,
  p_customer_id uuid default null,
  p_customer_name text default null,
  p_customer_phone text default null,
  p_payment_method text default 'Pesapal',
  p_shift_id uuid default null,
  p_cashier_id uuid default null,
  p_confirmed boolean default false
)
returns table (id bigint, total_amount numeric)
language plpgsql
security definer
set search_path = public
as $$
declare
  requested record;
  product_row record;
  created_order_id bigint;
  calculated_total numeric(12, 2) := 0;
begin
  if jsonb_typeof(p_items) <> 'array' or jsonb_array_length(p_items) = 0 then
    raise exception 'Cart items are required.' using errcode = '22023';
  end if;

  -- Aggregate duplicate product IDs and lock rows in ID order to avoid
  -- overselling and reduce deadlock risk when carts overlap.
  for requested in
    select value->>'productId' as product_id,
           sum((value->>'quantity')::integer)::integer as quantity
    from jsonb_array_elements(p_items) as item(value)
    group by value->>'productId'
    order by (value->>'productId')::bigint
  loop
    if requested.quantity < 1 or requested.quantity > 100 then
      raise exception 'Invalid product quantity.' using errcode = '22023';
    end if;

    select p.id, p.name, p.price, p.stock_quantity, p.stock_reserved
    into product_row
    from public.products p
    where p.id = requested.product_id::bigint
    for update;

    if not found then
      raise exception 'Product % is unavailable.', requested.product_id using errcode = 'P0001';
    end if;

    if coalesce(product_row.stock_quantity, 0) - coalesce(product_row.stock_reserved, 0) < requested.quantity then
      raise exception 'Insufficient stock for product %.', requested.product_id using errcode = 'P0001';
    end if;

    calculated_total := calculated_total + (product_row.price * requested.quantity);
    update public.products
    set stock_reserved = coalesce(stock_reserved, 0) + requested.quantity
    where public.products.id = product_row.id;
  end loop;

  insert into public.orders (
    customer_id, shift_id, cashier_id, customer_name, customer_phone,
    total_amount, payment_method, status
  ) values (
    p_customer_id, p_shift_id, p_cashier_id, nullif(trim(p_customer_name), ''),
    nullif(trim(p_customer_phone), ''), calculated_total, p_payment_method,
    case when p_confirmed then 'completed' else 'pending' end
  ) returning public.orders.id into created_order_id;

  update public.orders
  set inventory_status = case when p_confirmed then 'finalized' else 'reserved' end
  where public.orders.id = created_order_id;

  for requested in
    select value->>'productId' as product_id,
           sum((value->>'quantity')::integer)::integer as quantity
    from jsonb_array_elements(p_items) as item(value)
    group by value->>'productId'
  loop
    select p.name, p.price
    into product_row
    from public.products p
    where p.id = requested.product_id::bigint;

    insert into public.order_items (
      order_id, product_id, product_name, unit_price, quantity, subtotal
    ) values (
      created_order_id, requested.product_id::bigint, product_row.name, product_row.price,
      requested.quantity, product_row.price * requested.quantity
    );
  end loop;

  if p_confirmed then
    for requested in
      select value->>'productId' as product_id,
             sum((value->>'quantity')::integer)::integer as quantity
      from jsonb_array_elements(p_items) as item(value)
      group by value->>'productId'
    loop
      update public.products
      set stock_quantity = coalesce(stock_quantity, 0) - requested.quantity,
          stock_reserved = stock_reserved - requested.quantity
      where public.products.id = requested.product_id::bigint;
    end loop;
  end if;

  return query select created_order_id, calculated_total;
end;
$$;

create or replace function public.finalize_order_inventory(
  p_order_id bigint,
  p_new_status text
)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  current_order record;
  line record;
begin
  select id, status, inventory_status into current_order
  from public.orders
  where public.orders.id = p_order_id
  for update;

  if not found or current_order.status <> 'pending' or current_order.inventory_status <> 'reserved' then
    return;
  end if;

  for line in
    select product_id, quantity
    from public.order_items
    where order_id = p_order_id
  loop
    if p_new_status = 'completed' then
      update public.products
      set stock_quantity = coalesce(stock_quantity, 0) - line.quantity,
          stock_reserved = stock_reserved - line.quantity
      where public.products.id = line.product_id::bigint;
    elsif p_new_status in ('failed', 'cancelled', 'expired') then
      update public.products
      set stock_reserved = stock_reserved - line.quantity
      where public.products.id = line.product_id::bigint;
    else
      raise exception 'Unsupported inventory status %.', p_new_status using errcode = '22023';
    end if;
  end loop;

  update public.orders
  set status = p_new_status,
      inventory_status = case when p_new_status = 'completed' then 'finalized' else 'released' end,
      updated_at = now()
  where public.orders.id = p_order_id;
end;
$$;

create or replace function public.expire_stale_order_reservations(
  p_timeout interval default interval '30 minutes'
)
returns integer
language plpgsql
security definer
set search_path = public
as $$
declare
  pending_order record;
  expired_count integer := 0;
begin
  for pending_order in
    select id
    from public.orders
    where status = 'pending'
      and inventory_status = 'reserved'
      and created_at < now() - p_timeout
    for update skip locked
  loop
    perform public.finalize_order_inventory(pending_order.id, 'expired');
    expired_count := expired_count + 1;
  end loop;
  return expired_count;
end;
$$;

